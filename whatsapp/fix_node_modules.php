<?php
header('Content-Type: text/plain');

$app_dir = '/home/shacartc/whatsapp-service';
$symlink = "$app_dir/node_modules";

echo "=== Current symlink info ===\n";
if (is_link($symlink)) {
    echo "node_modules is a symlink pointing to: " . readlink($symlink) . "\n";
    echo "Attempting to delete symlink...\n";
    if (unlink($symlink)) {
        echo "Successfully deleted symlink.\n";
    } else {
        echo "Failed to delete symlink.\n";
        exit;
    }
} else {
    echo "node_modules is not a symlink.\n";
}

echo "\n=== Running npm install to create real node_modules folder ===\n";
// Run npm install in the app directory using the virtualenv's npm binary
$npm_path = '/home/shacartc/nodevenv/whatsapp-service/20/bin/npm';
$cmd = "cd $app_dir && $npm_path install 2>&1";
echo "Executing: $cmd\n";
$output = shell_exec($cmd);
echo "Output:\n$output\n";

echo "\n=== Verifying resulting node_modules ===\n";
echo shell_exec("ls -la $app_dir 2>&1");
echo shell_exec("ls -la $app_dir/node_modules | head -n 20 2>&1");

echo "\n=== Restarting Node app ===\n";
if (file_exists("$app_dir/tmp")) {
    $restart_file = "$app_dir/tmp/restart.txt";
    touch($restart_file);
    echo "Touched $restart_file\n";
} else {
    echo "tmp folder does not exist, creating it...\n";
    mkdir("$app_dir/tmp", 0755, true);
    touch("$app_dir/tmp/restart.txt");
    echo "Created and touched tmp/restart.txt\n";
}
